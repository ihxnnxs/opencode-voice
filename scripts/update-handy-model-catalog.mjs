import fs from "node:fs";
import path from "node:path";
import { createHash } from "node:crypto";

const API = "https://huggingface.co/api/models?author=handy-computer&limit=100";
const output = path.resolve("lib/handy-model-catalog.js");
const preferredQuantizations = ["Q4_K_M", "Q5_K_M", "Q8_0", "Q6_K", "Q5_0", "Q4_0", "F16", "BF16"];

function id(value) {
  return `handy-${value.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "")}`;
}

function pickArtifact(files) {
  const gguf = files.filter((file) => file.path.endsWith(".gguf") && file.lfs?.oid && file.size > 0);
  for (const quantization of preferredQuantizations) {
    const match = gguf.find((file) => new RegExp(`-${quantization.replace(/_/g, "_")}\\.gguf$`, "i").test(file.path));
    if (match) return match;
  }
  return gguf[0];
}

async function json(url) {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);
  return response.json();
}

const summaries = await json(API);
const sourceModels = summaries.filter((model) => model.library_name === "transcribe.cpp" && model.pipeline_tag === "automatic-speech-recognition");
if (sourceModels.length < 67) throw new Error(`Refusing to shrink the Handy catalog below 67 ASR models (received ${sourceModels.length})`);
const models = [];

for (const summary of sourceModels.sort((a, b) => a.id.localeCompare(b.id))) {
  const detail = await json(`https://huggingface.co/api/models/${summary.id}`);
  const files = await json(`https://huggingface.co/api/models/${summary.id}/tree/${detail.sha}?recursive=false&expand=true`);
  const artifact = pickArtifact(files);
  if (!artifact) throw new Error(`No verified GGUF artifact for ${summary.id}`);

  const architecture = detail.gguf?.architecture || "transcribe.cpp";
  const languages = Array.isArray(detail.cardData?.language) ? detail.cardData.language.join(", ") : "model-defined languages";
  models.push({
    id: id(summary.id.replace(/^handy-computer\//, "")),
    name: summary.id.replace(/^handy-computer\//, ""),
    engine: "transcribe-cpp",
    implemented: true,
    filename: artifact.path,
    url: `https://huggingface.co/${summary.id}/resolve/${detail.sha}/${encodeURIComponent(artifact.path)}`,
    sha256: artifact.lfs.oid,
    sizeMB: Math.ceil(artifact.size / 1024 / 1024),
    languages,
    description: `${architecture} model from Handy's transcribe.cpp catalog. Pinned to ${detail.sha.slice(0, 12)}.`,
  });
}

const serialized = JSON.stringify(models, null, 2);
const digest = createHash("sha256").update(serialized).digest("hex");
const source = `// Generated by scripts/update-handy-model-catalog.mjs. Do not edit manually.\nexport const HANDY_MODEL_CATALOG_SHA256 = "${digest}";\nexport const HANDY_MODELS = ${serialized};\n`;
await fs.promises.writeFile(output, source);
console.log(`Wrote ${models.length} verified Handy ASR models to ${output} (${digest})`);
